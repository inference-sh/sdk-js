/** Header value from various HTTP libraries */
export type HttpHeaderValue = string | string[] | undefined | null;

/**
 * Framework adapter interface for proxy handlers.
 * Implement this to support a new framework.
 */
export interface ProxyAdapter<T, R = unknown> {
    /** Framework name for user-agent */
    framework: string;

    /** The framework's request, handed to `isAuthenticated` */
    request?: R;

    /** HTTP method of the request */
    method: string;

    /** Get request body as string */
    body: () => Promise<string | undefined>;

    /** Get all request headers */
    headers: () => Record<string, HttpHeaderValue>;

    /** Get single header value */
    header: (name: string) => HttpHeaderValue;

    /** Get query parameter (optional, for SSE fallback) */
    query?: (name: string) => string | undefined;

    /** Set response header */
    setHeader: (name: string, value: string) => void;

    /** Send error response */
    error: (status: number, message: string | object) => T;

    /** Pass through fetch Response */
    respond: (response: Response) => Promise<T>;

    /** Custom API key resolver (optional) */
    apiKey?: () => Promise<string | undefined>;

    /**
     * Aborts the upstream request (optional). Adapters that copy the
     * upstream body themselves abort it when their client disconnects, so a
     * stream nobody reads any more (GET /chats/{id}/stream never ends on its
     * own) does not stay open.
     */
    signal?: AbortSignal;
}

/**
 * Proxy handler options.
 */
export interface ProxyOptions<R = unknown> {
    /** Custom API key (defaults to INFERENCE_API_KEY env var) */
    apiKey?: string;

    /**
     * The API the frontend's SDK client calls (its `baseUrl`), default
     * https://api.inference.sh. The proxy attaches the key only to requests
     * for this origin (or an `allowedDomains` host); a target on any other
     * host, other inference.sh hosts included, is refused with 412.
     */
    apiUrl?: string;

    /**
     * Rewrite every target to this API base (defaults to the
     * INFERENCE_API_BASE_URL env var). When set, it is also the only origin
     * the proxy forwards to.
     */
    apiBaseUrl?: string;

    /**
     * Extra target hosts, besides the API's. Each pattern must match the
     * whole host (`host:port` when the target names a port).
     */
    allowedDomains?: RegExp[];

    /**
     * Largest file, in bytes, a visitor may upload through the proxy
     * (default 100 MiB). `POST /files` declares each file's size and the API
     * binds the upload URL to it; the bytes then go straight to storage and
     * count against the API key owner's storage quota. One file per request.
     */
    maxUploadBytes?: number;

    /**
     * Apps and agents visitors may run, as `namespace/name` globs: "ana/helper",
     * or "ana/*" for all of a namespace. Unset or empty allows every app and
     * agent the API key can run.
     *
     * Checked where a request names the app or agent: a new app run, a new
     * chat or agent message, a chat handed to another agent, an agent's info.
     * Requests about an existing task or chat name it by id, and the proxy
     * cannot tell which app or agent that is: whoever holds a task or chat id
     * can read and stream it, cancel or stop it, and send messages in the
     * chat (which run the chat's agent). All visitors share one key, so the
     * id is the only boundary between them. When set, ad-hoc agent configs
     * (`agent_config`) and runs by `app_id`/`version_id` are refused.
     */
    allowedEndpoints?: string[];

    /**
     * Match `allowedEndpoints` entries against the whole ref, version and
     * function included, instead of as `namespace/name` globs: the entry
     * "ana/helper@v2" lets only that exact ref through, and "ana/helper"
     * only the unversioned ref. Entries are refs, without `*`.
     */
    exactRefs?: boolean;

    /**
     * The calls to forward, a subset of PROXY_ENDPOINTS (default: all of
     * them). Entries must come from PROXY_ENDPOINTS or `pickProxyEndpoint`,
     * which can narrow one further but never widen it; anything else
     * refuses every request with 500.
     */
    endpoints?: readonly ProxyEndpoint[];

    /**
     * Decides whether a request may use the API key, e.g. by checking your
     * session. Requests it answers false for are refused with 401. Receives
     * the framework's request (NextRequest, Express Request, Hono Context, ...).
     */
    isAuthenticated?: (request: R) => boolean | Promise<boolean>;

    /**
     * Without `isAuthenticated`, whether anyone may use the proxy (default
     * true, for compatibility). Set it to false to require `isAuthenticated`:
     * with neither, every request is refused.
     */
    allowUnauthorizedRequests?: boolean;
}

